    /// FoodIncludesAnimalProtein 点火時に主食の必要量をこの比で譲る（バスケットに肉が入った分だけ穀物の取り分が減る＝
    /// 総食料需要を中立に保つ。野菜(108)追加時にパンを0.80→0.55へ譲った前例と同じ処理をデータから導出）。現行データでは 0.22/1.10=0.2。</summary>
