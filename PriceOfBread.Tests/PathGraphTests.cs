    private static void AssertBand(double graphKm, double actualKm)
    {
        double ratio = graphKm / actualKm;
        Assert.True(ratio is >= 0.6 and <= 1.7, $"許容帯外: グラフ{graphKm:F0}km / 実際{actualKm}km = ×{ratio:F2}");
    }

    [Fact]
    public void 代表経路が許容帯に収まる()
    {
        AssertBand(PathGraph.LandDistanceKm(45.46, 9.19, 48.14, 11.58), 590);     // ミラノ→ミュンヘン（アルプス迂回）
        AssertBand(PathGraph.LandDistanceKm(40.42, -3.7, 48.85, 2.35), 1450);     // マドリード→パリ（ピレネー迂回）
        AssertBand(PathGraph.LandDistanceKm(50.94, 6.96, 40.85, 14.27), 1600);    // ケルン→ナポリ
        AssertBand(PathGraph.LandDistanceKm(48.85, 2.35, 43.3, 5.37), 863);       // パリ→マルセイユ（国内幹線）
        // ★2026-08-02：デリー→ラサは**距離だけでは番人にならない**。実測1355kmは大圏1353kmとほぼ同じなので、
        //   ヒマラヤを直線で貫通した辺が ×1.00 で満点を取ってしまう（実際にそうなっていた＝経路が「デリー→ラサ」の2ホップ）。
        //   ★距離ではなく**経路の形**を見る＝山越えは峠を通るはずである（ニャラム峠＝カトマンズとラサを結んだ史実の交易路）。
        AssertBand(PathGraph.LandDistanceKm(28.61, 77.21, 29.65, 91.1), 1355 * 1.5);   // 迂回込みの実距離（直行は不可）
    }

    [Fact]
    public void ヒマラヤは直行できず峠を通る()
    {
        // ★2026-08-02：バリアの密度が足りずデリー→ラサが直行していた（エベレストまで138km＞閾値110km＝すり抜け）。
        // 稜線に8点を足して壁を閉じ、史実の峠（ニャラム＝カトマンズとラサの交易路）を置いた。
        // ⚠この検査は**距離ではなく経路の形**を見る。距離だけだと直行が満点を取る（上の帯コメント参照）。
        var path = PathGraph.RoutePath(28.61, 77.21, 29.65, 91.1);
        Assert.True(path.Count >= 3, "デリー→ラサが直行している（ヒマラヤを貫通）: " + string.Join("→", path));
        Assert.True(path.Exists(n => n.Contains("峠", StringComparison.Ordinal)),
            "峠を通っていない＝山を貫通している: " + string.Join("→", path));
    }

    [Fact]
    public void アルプス直行辺は存在せず経路が迂回する()
    {
        // ミラノ↔ミュンヘンの直接辺が無い（バリアがk枠を食い、山脈の向こうへ辺が張られない）＝迂回は経路として出る
        int mi = -1, mu = -1;
        for (int i = 0; i < PathGraph.Nodes.Length; i++)
        {
            if (PathGraph.Nodes[i].Name == "ミラノ") mi = i;
            if (PathGraph.Nodes[i].Name == "ミュンヘン") mu = i;
        }
        Assert.True(mi >= 0 && mu >= 0);
        foreach (var e in PathGraph.Edges)
            Assert.False((e.A == mi && e.B == mu) || (e.A == mu && e.B == mi), "ミラノ↔ミュンヘンに直行辺（アルプス貫通）がある");
        var path = PathGraph.RoutePath(45.46, 9.19, 48.14, 11.58);
        Assert.True(path.Count >= 3, "迂回経路が出ていない: " + string.Join("→", path));
    }

