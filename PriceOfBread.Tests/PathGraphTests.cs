    /// <summary>#19c（2026-09-11）：大圏弧の交差判定の唯一定義（Runner の壁検査が同じ1本と交点を読む）。赤道弧（経度−45..45）と本初子午線弧（緯度−45..45）は (1,0,0) で交わり、
    /// 経度80の子午線弧は赤道弧の外＝交わらない。退化（同じ大圏）は否定形で「交わらない」。</summary>
    [Fact]
    public void 大圏弧の交差は交点を返し外れた弧と退化は交わらない()
    {
        double h = System.Math.Sqrt(0.5);
        var a = (h, -h, 0.0); var b = (h, h, 0.0);   // 赤道 lon −45..45
        var c = (h, 0.0, -h); var d = (h, 0.0, h);   // 子午線 lon 0・lat −45..45
        Assert.True(PathGraph.ArcsCross(a, b, c, d, out var p), "直交する2弧が交わらない");
        Assert.True(System.Math.Abs(p.X - 1) < 1e-9 && System.Math.Abs(p.Y) < 1e-9 && System.Math.Abs(p.Z) < 1e-9, $"交点が (1,0,0) でない：{p}");
        double c80 = System.Math.Cos(80 * System.Math.PI / 180), s80 = System.Math.Sin(80 * System.Math.PI / 180);
        var c2 = (h * c80, h * s80, -h); var d2 = (h * c80, h * s80, h);   // 子午線 lon 80＝赤道弧の外で赤道を横切る
        Assert.False(PathGraph.ArcsCross(a, b, c2, d2, out var q), "弧の外の交点を交差と数えた");
        Assert.Equal((0.0, 0.0, 0.0), q);
        Assert.False(PathGraph.ArcsCross(a, b, a, b, out _), "同じ大圏（退化）を交差と数えた");
    }
