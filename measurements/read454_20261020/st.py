import json,sys,math
sys.stdout.reconfigure(encoding='utf-8')
R=json.load(open('ref.json',encoding='utf-8'))
LAB=0.25; VA=0.06
def adv(n): 
    a={'電力':0.15}.get(n); 
    if a: return a*0.8
    if n in('機械','蒸気機関','電化製品','汽船','機関車','送電網','内燃機関'): return 0.08
    if n in('鉄','鋼','銅','鉛','セメント','ガラス','化学薬品','火薬'): return 0.04
    return 0.016
rows={ # name: (good, inputs, old price ref)
 '甜菜糖':('砂糖',{'果実':2.2,'化学薬品':0.15}),
 '魚の缶詰':('缶詰',{'魚':0.6,'鉄':0.3,'塩':0.2}),
 '黄鉄鉱法':('化学薬品',{'鉄鉱石':0.6,'石炭':0.8,'塩':0.4}),
 '石油灯油':('灯油',{'原油':1.0}),
 '石油ケロシン':('灯油',{'原油':0.5}),
 '鉄筋コンクリート':('住居',{'セメント':0.3,'鋼':0.2}),
 'クロムなめし':('革',{'畜産':0.5,'クロム鉱':0.08}),
 '無煙火薬':('火薬',{'化学薬品':0.3,'硝石':0.2,'石炭':0.05}),
 '水力発電':('電力',{'機械':0.647}),
 '蒸気タービン':('電力',{'機械':0.199,'石炭':0.6}),
 '石油火力':('電力',{'機械':0.498,'原油':0.6}),
 '人絹':('絹織物',{'製材':0.4,'化学薬品':0.5}),
 '窒素固定':('肥料',{'化学薬品':0.15,'電力':0.25}),
 '合成ゴム':('ゴム',{'化学薬品':0.5,'石炭':0.3}),
 '合成染料':('染料',{'化学薬品':0.7}),
}
for k,(g,inp) in rows.items():
    c=VA+LAB+adv(g)+sum(q*R.get(n,float('nan')) for n,q in inp.items())
    dom=max(inp.items(),key=lambda t:t[1]*R.get(t[0],0))
    print(f"{k}: C_new={c:.3f} P_old(ref)={R[g]:.3f} ln={math.log(R[g]/c):+.2f} 最大の投入={dom[0]}×{dom[1]}={dom[1]*R[dom[0]]:.2f}({dom[1]*R[dom[0]]/c:.0%})")
print('steam labor', 0.175+0.02*R['蒸気機関']+0.3*R['石炭'], 'vs 0.5')
print('electric motor', 0.14+0.25*R['電力'])
