"""(333) 初期値 段4 C2＝南アジアの人口の仕様（事前登録と同じ値）。単位＝千人。確からしさ S＝出典の表を取得して検算した／R＝【推】記憶・補間・判定。
"""
import math

# --- 史実の側（BCG＝Broadberry, Custodis & Gupta 2015, India and the Great Divergence, EEH 55, Table 1。範囲＝本文「亜大陸、パキスタンとバングラデシュを含む現在のインド」） ---
BCG = {1600: 142, 1650: 142, 1700: 164, 1750: 190, 1801: 207, 1811: 215, 1821: 205, 1831: 216, 1841: 212, 1851: 232, 1861: 244, 1871: 256}   # 百万人 (S)
Y0 = 1783   # 開幕の年


def interp_loglinear(y, a=1750, b=1801):
    """BCG の 1750→1801 を対数線形で 1783 へ補間（BCG 本文が 1700 を埋めるのに使う方法と同じ）。【推・補間】"""
    return BCG[a] * math.exp(math.log(BCG[b] / BCG[a]) * (y - a) / (b - a))


TARGET_K = interp_loglinear(Y0) * 1000      # 千人 ≒ 200,776
WINDOW_K = (190_000, 211_000)               # 番人の幅＝BCG の 1750 の値 190 から 1801 の 207 の＋2% まで（補間値 ±5% を内に含む）
GROWTH_REF = 0.0030                         # 1801〜1871 の年率 0.30%（BCG Table 1 の年率の欄）(S)

# --- モデルの側：〈BCG の範囲〉に当たる勢力（ネパール・セイロンは範囲外＝据え置き） ---
INDEPENDENTS = ['マラータ同盟', 'マイソール', 'ハイデラバード', 'シク連邦', 'デリー', 'アワド']   # 国の行（階級の人数の和）
COLONIES = [('イギリス', '中核ベンガル'), ('イギリス', '内陸ベンガル'), ('イギリス', 'マドラス'), ('イギリス', 'ボンベイ'), ('フランス', 'ポンディシェリ')]   # 植民地の行（popK）
OUT_OF_RANGE = ['ネパール', ('ネーデルラント', 'セイロン')]

# 開幕の総数（千人）＝A（r331 と同じ木）の initdump seed 1789 の「人口/総数 開幕」。使用人の上乗せと兵士の引き算を含む（world.json の階級の和ではない）。
OPENING_A_K = {'マラータ同盟': 51300.0, 'マイソール': 6429.2, 'ハイデラバード': 13070.0, 'シク連邦': 6820.0, 'デリー': 1970.4, 'アワド': 8380.0}
COLONY_A_K = 26000.0 + 4000.0 + 250.0 + 170.0   # 中核15600＋内陸10400・マドラス・ボンベイ・ポンディシェリ（植民地の行は popK がそのまま州の人口）

# 据え置く国（出典または前の段の判定がある）＝B2 の錨
ANCHORS_B2 = ['マイソール', 'ハイデラバード', 'デリー']
ANCHOR_SRC = {
    'マイソール': '1782 約600万（WP Sultanate of Mysore 系・二次）(227) で置いた値',
    'ハイデラバード': '1867 約1,070万（theprint.in の要約・二次）。階級の和 11,750 は既に 1867 の約1.10倍',
    'デリー': '(227) で 381→180万（棚卸し担当の判定・直接の出典なし）',
}


def factors():
    """B1＝英領・仏領を据え置き、独立6国を一様に f1 倍。B2＝さらに ANCHORS_B2 を据え置き、残る 3国（マラータ・シク・アワド）を f2 倍。"""
    ind = sum(OPENING_A_K.values())
    f1 = (TARGET_K - COLONY_A_K) / ind
    fixed = sum(OPENING_A_K[n] for n in ANCHORS_B2)
    var = ind - fixed
    f2 = (TARGET_K - COLONY_A_K - fixed) / var
    return f1, f2


def arm_f(arm):
    f1, f2 = factors()
    return {'B1': {n: f1 for n in INDEPENDENTS},
            'B2': {n: (1.0 if n in ANCHORS_B2 else f2) for n in INDEPENDENTS}}[arm]

